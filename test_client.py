#!/usr/bin/env python3
"""
CLI Test Client for AI Document Analyzer.
Uses pure Python standard library (urllib.request) - no external packages required.
Works seamlessly across Windows, macOS, and Linux.

Usage:
    # 1. Check API Health
    python test_client.py health

    # 2. Upload and analyze a document
    python test_client.py upload test_samples/sample_contract.txt

    # 3. Query document insights by ID
    python test_client.py get <document_id>

    # 4. List recent document insights
    python test_client.py list
"""

import argparse
import json
import os
import sys
import time
import urllib.parse
import urllib.request


def load_api_endpoint() -> str:
    """Reads API endpoint from env var or cdk-outputs.json or .env."""
    # 1. Environment variable
    api_url = os.environ.get("API_URL")
    if api_url:
        return api_url.rstrip("/")

    # 2. cdk-outputs.json (auto-generated by deploy scripts)
    outputs_path = os.path.join(os.path.dirname(__file__), "cdk-outputs.json")
    if os.path.exists(outputs_path):
        try:
            with open(outputs_path, "r", encoding="utf-8") as f:
                data = json.load(f)
                for stack in data.values():
                    if "ApiEndpoint" in stack:
                        return stack["ApiEndpoint"].rstrip("/")
        except Exception:
            pass

    # 3. .env file
    env_path = os.path.join(os.path.dirname(__file__), ".env")
    if os.path.exists(env_path):
        try:
            with open(env_path, "r", encoding="utf-8") as f:
                for line in f:
                    if line.startswith("API_URL="):
                        return line.split("=", 1)[1].strip().rstrip("/")
        except Exception:
            pass

    print("[!] ERROR: API_URL not found.")
    print("Please export API_URL or deploy using ./deploy.ps1 or ./deploy.sh.")
    print("Example: set API_URL=https://xxxxxxxxxx.execute-api.us-east-1.amazonaws.com")
    sys.exit(1)


def make_http_request(url: str, method: str = "GET", data: bytes = None, headers: dict = None) -> tuple[int, bytes]:
    """Helper to perform HTTP requests using standard urllib."""
    headers = headers or {}
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req) as response:
            return response.status, response.read()
    except urllib.error.HTTPError as err:
        return err.code, err.read()
    except Exception as err:
        print(f"[!] Network error connecting to {url}: {err}")
        sys.exit(1)


def cmd_health(api_url: str):
    """Checks API health."""
    print(f"--> Pinging API Health: {api_url}/health")
    code, body = make_http_request(f"{api_url}/health")
    print(f"Status Code: {code}")
    print(json.dumps(json.loads(body.decode("utf-8")), indent=2))


def cmd_upload(api_url: str, file_path: str):
    """Requests presigned URL, uploads file to S3, and polls for extraction."""
    if not os.path.exists(file_path):
        print(f"[!] File not found: {file_path}")
        sys.exit(1)

    filename = os.path.basename(file_path)
    file_size = os.path.getsize(file_path)
    with open(file_path, "rb") as f:
        file_bytes = f.read()

    # Determine content-type
    content_type = "text/plain"
    if filename.lower().endswith(".json"):
        content_type = "application/json"
    elif filename.lower().endswith(".pdf"):
        content_type = "application/pdf"

    print("================================================================")
    print(f"  Uploading Document: {filename} ({file_size} bytes)")
    print("================================================================")

    # Step 1: Request presigned S3 PUT URL
    print("--> Step 1/3: Requesting S3 presigned upload URL from API Gateway...")
    req_payload = json.dumps({"filename": filename, "content_type": content_type}).encode("utf-8")
    code, res_body = make_http_request(
        f"{api_url}/upload-url",
        method="POST",
        data=req_payload,
        headers={"Content-Type": "application/json"}
    )

    if code != 200:
        print(f"[!] Failed to obtain upload URL (HTTP {code}): {res_body.decode('utf-8')}")
        sys.exit(1)

    url_data = json.loads(res_body.decode("utf-8"))
    doc_id = url_data["document_id"]
    upload_url = url_data["upload_url"]
    print(f"[+] Document ID Assigned: {doc_id}")
    print(f"[+] S3 Target Key:       {url_data.get('s3_key')}")

    # Step 2: Direct S3 PUT Upload
    print("--> Step 2/3: Uploading file directly to S3 via presigned PUT...")
    put_code, put_body = make_http_request(
        upload_url,
        method="PUT",
        data=file_bytes,
        headers={"Content-Type": content_type}
    )

    if put_code not in [200, 204]:
        print(f"[!] S3 upload failed (HTTP {put_code}): {put_body.decode('utf-8')}")
        sys.exit(1)

    print("[+] File uploaded directly to S3 successfully!")
    print("--> Step 3/3: Waiting for Bedrock processing (S3 trigger -> Lambda -> Bedrock)...")

    # Step 3: Poll DynamoDB for completion
    max_wait_seconds = 45
    poll_interval = 3
    start_time = time.time()

    while (time.time() - start_time) < max_wait_seconds:
        time.sleep(poll_interval)
        print(f"    Checking status... ({int(time.time() - start_time)}s elapsed)")
        q_code, q_body = make_http_request(f"{api_url}/insights/{doc_id}")
        if q_code == 200:
            result = json.loads(q_body.decode("utf-8"))
            if result.get("status") == "COMPLETED":
                print("\n================================================================")
                print(f"  AI Extraction Complete ({int(time.time() - start_time)}s total latency)")
                print("================================================================")
                print(json.dumps(result, indent=2))
                return
            elif result.get("status") == "FAILED":
                print(f"\n[!] Document processing failed: {result.get('error_message')}")
                return

    print(f"\n[!] Polling timed out after {max_wait_seconds}s. Document may still be processing.")
    print(f"You can query it manually using: python test_client.py get {doc_id}")


def cmd_get(api_url: str, doc_id: str):
    """Queries insights for a single document ID."""
    print(f"--> Querying insights for document: {doc_id}")
    code, body = make_http_request(f"{api_url}/insights/{doc_id}")
    if code == 200:
        data = json.loads(body.decode("utf-8"))
        print(json.dumps(data, indent=2))
    elif code == 404:
        print(f"[!] Document {doc_id} not found or still processing.")
    else:
        print(f"[!] Error (HTTP {code}): {body.decode('utf-8')}")


def cmd_list(api_url: str, limit: int = 20):
    """Lists recent documents from DynamoDB."""
    print(f"--> Listing recent documents (limit={limit})...")
    code, body = make_http_request(f"{api_url}/insights?limit={limit}")
    if code == 200:
        data = json.loads(body.decode("utf-8"))
        print(json.dumps(data, indent=2))
    else:
        print(f"[!] Error (HTTP {code}): {body.decode('utf-8')}")


def main():
    parser = argparse.ArgumentParser(description="AI Document Analyzer CLI Test Client")
    subparsers = parser.add_subparsers(dest="command", required=True)

    # Health
    subparsers.add_parser("health", help="Check API health")

    # Upload
    upload_parser = subparsers.add_parser("upload", help="Upload a document and wait for AI insights")
    upload_parser.add_argument("file", help="Path to document file (TXT, JSON, PDF)")

    # Get
    get_parser = subparsers.add_parser("get", help="Fetch insights for a document ID")
    get_parser.add_argument("id", help="Document UUID")

    # List
    list_parser = subparsers.add_parser("list", help="List recent document insights")
    list_parser.add_argument("--limit", type=int, default=20, help="Maximum number of items to return")

    args = parser.parse_args()
    api_url = load_api_endpoint()

    if args.command == "health":
        cmd_health(api_url)
    elif args.command == "upload":
        cmd_upload(api_url, args.file)
    elif args.command == "get":
        cmd_get(api_url, args.id)
    elif args.command == "list":
        cmd_list(api_url, args.limit)


if __name__ == "__main__":
    main()
